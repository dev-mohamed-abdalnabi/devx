/// أقرب مدينة في القائمة ضمن [maxKm] كيلومتر، أو NULL.
City? nearestCity(double lat, double lng, {double maxKm = 60}) {
  City? best;
  var bestKm = double.infinity;
  for (final c in cities) {
    final dLat = (c.lat - lat) * math.pi / 180;
    final dLng = (c.lng - lng) * math.pi / 180;
    final a = math.pow(math.sin(dLat / 2), 2) +
        math.cos(lat * math.pi / 180) *
            math.cos(c.lat * math.pi / 180) *
            math.pow(math.sin(dLng / 2), 2);
    final km = 2 * 6371 * math.asin(math.sqrt(a.toDouble()));
    if (km < bestKm) {
      bestKm = km;
      best = c;
    }
  }
  return bestKm <= maxKm ? best : null;
}
