def norm(s: str) -> str:
    s = re.sub("[\u064B-\u065F\u0670\u0640\u06D6-\u06ED]", "", s)
    for a in "أإآٱ":
        s = s.replace(a, "ا")
    return s.replace("ى", "ي").replace("ة", "ه")


def load_hadith():
    books = {}
    for b in ("bukhari", "muslim"):
        p = LIB / f"{b}.json"
        if not p.exists():
            sys.exit(f"الملف {p} غير موجود: شغّل tool/fetch_library.py أولًا")
        d = json.loads(p.read_text(encoding="utf-8"))
        books[b] = {n: t for ch in d["chapters"] for n, t in ch["h"]}
    return books


def verify(parts, books, errors, where):
    for p in parts:
        if p["k"] == "quran":
            s, a, b = p["s"], p["from"], p["to"]
            if not (1 <= s <= 114 and 1 <= a <= b <= AYAH_COUNTS[s - 1]):
                errors.append(f"{where}: مدى آيات غير صالح {s}:{a}-{b}")
        else:
            t = books[p["b"]].get(p["n"])
            if t is None:
                errors.append(f"{where}: {p['b']} #{p['n']} غير موجود")
            elif norm(p["anchor"]) not in norm(t):
                errors.append(f"{where}: {p['b']} #{p['n']} لا يحتوي «{p['anchor']}»")


def build():
    books = load_hadith()
    errors: list[str] = []
    ids = set()

    def entry(eid, title, parts, section, extra=None):
        key = (section, eid)
        if key in ids:
            errors.append(f"معرّف مكرر {key}")
        ids.add(key)
        verify(parts, books, errors, f"{section}/{eid}")
        e = {"id": f"{section}:{eid}", "title": title, "parts": parts}
        if eid in KW:
            e["kw"] = KW[eid]
        if extra:
            e.update(extra)
        return e

    sections = [
        {"id": "quran", "title": "قصص القرآن",
         "subtitle": "قصص وردت في القرآن الكريم",
         "entries": [entry(i, t, p, "quran") for i, t, p in QURAN_STORIES
                     if i in QURAN_ONLY]},
        {"id": "prophets", "title": "على خُطى الأنبياء",
         "subtitle": "من آدم إلى عيسى عليهم السلام",
         "entries": [entry(i, t, qs + hs, "prophets") for i, t, qs, hs in PROPHETS]},
        {"id": "seerah", "title": "السيرة العَطِرة",
         "subtitle": "من البعثة إلى الوفاة ﷺ",
         "entries": [entry(i, t, p, "seerah", {"era": era}) for i, t, era, p in SEERAH]},
    ]
    return errors, {"version": 1, "sections": sections}


def main():
    errors, data = build()
    if errors:
        print("\n".join(errors))
        sys.exit(1)
    n = sum(len(s["entries"]) for s in data["sections"])
    refs = sum(len(e["parts"]) for s in data["sections"] for e in s["entries"])
    if "--check" not in sys.argv:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"ok: {n} مدخلًا، {refs} مرجعًا")


if __name__ == "__main__":
    main()
