-- إصدارات التطبيق ونظام التحديث من خارج المتجر.
create table if not exists public.app_releases (
  id bigint generated by default as identity primary key,
  version_name text not null check (char_length(trim(version_name)) between 1 and 30),
  version_code integer not null check (version_code > 0),
  download_page_url text not null check (download_page_url like 'https://%'),
  apk_url text not null check (apk_url like 'https://%'),
  release_notes text not null default '' check (char_length(release_notes) <= 4000),
  is_required boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (version_code)
);

alter table public.app_releases enable row level security;

drop policy if exists app_releases_public_read on public.app_releases;
create policy app_releases_public_read on public.app_releases
for select using (is_active = true);

drop policy if exists app_releases_admin_read on public.app_releases;
create policy app_releases_admin_read on public.app_releases
for select using (public.current_user_is_admin());

drop policy if exists app_releases_admin_insert on public.app_releases;
create policy app_releases_admin_insert on public.app_releases
for insert with check (public.current_user_is_admin());

drop policy if exists app_releases_admin_update on public.app_releases;
create policy app_releases_admin_update on public.app_releases
for update using (public.current_user_is_admin())
with check (public.current_user_is_admin());

drop policy if exists app_releases_admin_delete on public.app_releases;
create policy app_releases_admin_delete on public.app_releases
for delete using (public.current_user_is_admin());

create index if not exists app_releases_active_version_idx
  on public.app_releases (is_active, version_code desc);
